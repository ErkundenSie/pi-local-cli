import { createHash, randomUUID } from 'node:crypto';
import { mkdir, lstat, readFile, readdir, realpath, rename, rm, stat, writeFile } from 'node:fs/promises';
import { isAbsolute, join } from 'node:path';

const hash = value => createHash('sha256').update(value).digest('hex');
const digest = /^[a-f0-9]{64}$/;
const stateFile = /^[a-f0-9]{64}\.json$/;
const temporaryFile = /^[a-f0-9]{64}\.[a-f0-9-]{36}\.(?:tmp|take)$/;
const leaseId = /^[a-f0-9-]{36}$/;
const leaseFile = /^[a-f0-9-]{36}\.lease$/;
const leaseTemp = /^[a-f0-9-]{36}\.[a-f0-9-]{36}\.lease-tmp$/;

function alive(pid) {
  if (!pid) return false;
  try { process.kill(pid, 0); return true; }
  catch (error) { return error?.code !== 'ESRCH'; }
}
const maxFiles = 64;
const maxAgeMs = 6 * 60 * 60 * 1000;

// Do not include the rolling temporary path or authentication material.
// The settings file is generated by the plugin and contains tool policy only.
export async function agyLaunchHash({ file, args, cwd, env }) {
  const settings = join(cwd, 'gateway-settings.json');
  const exe = await realpath(file);
  const metadata = await stat(exe);
  const policy = await readFile(settings, 'utf8');
  const home = ['HOME', 'USERPROFILE', 'GEMINI_CLI_HOME', 'XDG_CONFIG_HOME', 'XDG_DATA_HOME'].map(key => env[key]);
  return hash(JSON.stringify([exe, metadata.size, metadata.mtimeMs, args.map(arg => arg === settings ? '<policy>' : arg), policy, home]));
}

function valid(row, ttlMs, now) {
  if (!row || (row.version !== 1 && !(row.version === 2 && typeof row.owner === 'string' && leaseId.test(row.owner)))) return false;
  const age = now - row.checkedAt;
  return Number.isSafeInteger(row.checkedAt) && age >= 0 && age < ttlMs &&
    typeof row.sessionId === 'string' && /^[a-zA-Z0-9._-]{1,128}$/.test(row.sessionId) &&
    typeof row.model === 'string' && /^[a-zA-Z0-9._-]{1,96}$/.test(row.model) &&
    typeof row.nativeModel === 'string' && /^(?:|[a-zA-Z0-9._-]{1,96})$/.test(row.nativeModel) &&
    typeof row.effort === 'string' && /^(?:|minimal|low|medium|high|xhigh|max)$/.test(row.effort) &&
    Number.isSafeInteger(row.historyLength) && row.historyLength > 1 &&
    [row.historyHash, row.toolConfig, row.launchHash].every(value => typeof value === 'string' && digest.test(value));
}

export function createCheckpointStore(directory, { ttlMs = maxAgeMs, now = Date.now } = {}) {
  if (!directory || !isAbsolute(directory) || !Number.isSafeInteger(ttlMs) || ttlMs <= 0) return undefined;
  const pathFor = scope => join(directory, hash(scope) + '.json');
  const tempFor = (scope, type) => join(directory, hash(scope) + '.' + randomUUID() + '.' + type);
  const leaseFor = id => join(directory, id + '.lease');

  async function writeAtomic(path, temp, value) {
    try {
      await writeFile(temp, JSON.stringify(value), { flag: 'wx', mode: 0o600 });
      await rename(temp, path);
      return true;
    } catch {
      await rm(temp, { force: true }).catch(() => {});
      return false;
    }
  }

  function writeLease(owner, pid, historyHash) {
    if (!leaseId.test(owner)) return false;
    return writeAtomic(leaseFor(owner), join(directory, `${owner}.${randomUUID()}.lease-tmp`), { pid, historyHash });
  }

  async function available(row) {
    if (row.version === 1) return true; // Older records were saved only after native close.
    try {
      const path = leaseFor(row.owner);
      const info = await lstat(path);
      if (!info.isFile() || info.size > 512) return false;
      const guard = JSON.parse(await readFile(path, 'utf8'));
      return guard.historyHash === row.historyHash && Number.isSafeInteger(guard.pid) && guard.pid >= 0 && !alive(guard.pid);
    } catch { return false; }
  }

  async function read(path) {
    try {
      const info = await lstat(path);
      if (!info.isFile() || info.size > 4096) return undefined;
      const row = JSON.parse(await readFile(path, 'utf8'));
      return valid(row, ttlMs, now()) ? row : undefined;
    } catch {
      return undefined;
    }
  }

  async function sweep() {
    const files = await readdir(directory, { withFileTypes: true });
    const active = [];
    await Promise.all(files.filter(file => file.isFile() && (stateFile.test(file.name) || temporaryFile.test(file.name) || leaseFile.test(file.name) || leaseTemp.test(file.name))).map(async file => {
      const path = join(directory, file.name);
      try {
        const { mtimeMs } = await lstat(path);
        if (now() - mtimeMs > ttlMs) await rm(path, { force: true });
        else if (stateFile.test(file.name)) active.push({ path, mtimeMs });
      } catch { /* Another instance can claim a record during cleanup. */ }
    }));
    await Promise.all(active.sort((a, b) => b.mtimeMs - a.mtimeMs).slice(maxFiles)
      .map(({ path }) => rm(path, { force: true }).catch(() => {})));
  }

  return {
    async save(scope, row, owner) {
      if (!scope) return false;
      const { sessionId, historyLength, historyHash, model, nativeModel, effort, toolConfig, launchHash } = row;
      const value = { version: owner ? 2 : 1, ...(owner && { owner }), checkedAt: now(),
        sessionId, historyLength, historyHash, model, nativeModel, effort, toolConfig, launchHash };
      if (!valid(value, ttlMs, now())) return false;
      try { await mkdir(directory, { recursive: true, mode: 0o700 }); }
      catch { return false; }
      // Publish the row first. An absent or nonmatching lease is never restorable.
      if (!await writeAtomic(pathFor(scope), tempFor(scope, 'tmp'), value)) return false;
      if (owner && !await writeLease(owner, process.pid, historyHash)) return false;
      await sweep().catch(() => {});
      return true;
    },
    markBusy(owner) { return writeLease(owner, process.pid, null); },
    unlock(owner, historyHash) { return writeLease(owner, 0, historyHash); },
    async take(scope, matches) {
      if (!scope) return undefined;
      const path = pathFor(scope);
      const candidate = await read(path);
      if (!candidate || !matches(candidate) || !await available(candidate)) return undefined;
      const claimed = tempFor(scope, 'take');
      // Rename is the single-use claim. Other processes must replay rather
      // than advancing the same native conversation concurrently.
      try { await rename(path, claimed); } catch { return undefined; }
      try {
        const row = await read(claimed);
        return row && matches(row) && await available(row) ? row : undefined;
      } finally {
        await rm(claimed, { force: true }).catch(() => {});
      }
    },
  };
}
